function normalizeCountryCode(countryCode) {
  if (!countryCode) return null;
  const raw = String(countryCode).toLowerCase();
  if (raw === "uk") return "gb";
  if (raw.startsWith("us-")) return "us";
  if (raw.startsWith("pt-")) return "pt";
  return raw.length === 2 ? raw : raw.slice(0, 2);
}

function hasUsefulState(stateLabel) {
  if (!stateLabel) return false;
  const s = String(stateLabel).trim();
  return s.length > 0 && s !== "—" && s !== "Unknown";
}

/** @returns {"south"|"central"|"north"} */
function latBand(lat, south, north) {
  const span = north - south;
  if (span <= 0) return "central";
  const t = (lat - south) / span;
  if (t < 1 / 3) return "south";
  if (t > 2 / 3) return "north";
  return "central";
}

/** @returns {"west"|"central"|"east"} */
function lngBand(lng, west, east) {
  let span = east - west;
  let lngNorm = lng;
  if (span < 0) {
    span += 360;
    lngNorm = lng < west ? lng + 360 : lng;
    const westNorm = west;
    const t = (lngNorm - westNorm) / span;
    if (t < 1 / 3) return "west";
    if (t > 2 / 3) return "east";
    return "central";
  }
  if (span <= 0) return "central";
  const t = (lngNorm - west) / span;
  if (t < 1 / 3) return "west";
  if (t > 2 / 3) return "east";
  return "central";
}

function capitalizeRegion(parts) {
  return parts
    .filter(Boolean)
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join("-");
}

function bboxQuadrantLabel(lat, lng, bbox) {
  const [south, north, west, east] = bbox;
  const ns = latBand(lat, south, north);
  const ew = lngBand(lng, west, east);

  if (ns === "central" && ew === "central") return "Central";

  if (ns === "central") {
    return capitalizeRegion([ew]);
  }
  if (ew === "central") {
    return capitalizeRegion([ns]);
  }
  return capitalizeRegion([ns, ew]);
}

/**
 * Primary: state/region name when geocoded.
 * Also adds bbox quadrant when it adds detail (e.g. "Southwest · Texas").
 */
function formatCountryPosition(lat, lng, countryCode, stateLabel) {
  const code = normalizeCountryCode(countryCode);
  const bbox = code ? COUNTRY_BBOXES[code] : null;
  const quadrant = bbox ? bboxQuadrantLabel(lat, lng, bbox) : null;
  const state = hasUsefulState(stateLabel) ? String(stateLabel).trim() : null;

  if (state) {
    if (quadrant && quadrant !== "Central") {
      return `${quadrant} · ${state}`;
    }
    return state;
  }

  return quadrant;
}

/** @deprecated Use formatCountryPosition */
function formatCountryCompass(lat, lng, countryCode, stateLabel) {
  return formatCountryPosition(lat, lng, countryCode, stateLabel);
}
